    pde.शब्दाः[0] = 0;

    pde.शब्दाः[0] |= (page_base_address & 0xffc00000) >> 0;
    pde.शब्दाः[0] |= (pat & 0x1) << 12;
    pde.शब्दाः[0] |= (avl & 0x7) << 9;
    pde.शब्दाः[0] |= (global & 0x1) << 8;
    pde.शब्दाः[0] |= (pde_pde_large & 0x1) << 7;
    pde.शब्दाः[0] |= (dirty & 0x1) << 6;
    pde.शब्दाः[0] |= (accessed & 0x1) << 5;
    pde.शब्दाः[0] |= (cache_disabled & 0x1) << 4;
    pde.शब्दाः[0] |= (write_through & 0x1) << 3;
    pde.शब्दाः[0] |= (super_user & 0x1) << 2;
